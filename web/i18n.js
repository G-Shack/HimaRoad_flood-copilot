const NE_PATTERNS = [
  [/^Scenario S(\d)( \(primary\))?, hypothetical$/, (m) => `परिदृश्य S${m[1]}${m[2] ? " (मुख्य)" : ""}, काल्पनिक`],
  [/^(\d+) potentially cut in S(\d) · click a row to find it on the map$/, (m) => `S${m[2]} मा ${m[1]} बस्तीको सम्पर्क टुट्न सक्छ · नक्सामा हेर्न पङ्क्तिमा क्लिक गर्नुहोस्`],
  [/^([\d,]+) mapped buildings$/, (m) => `${m[1]} नक्साङ्कित भवन`],
  [/^of (\d+)$/, (m) => `/ ${m[1]}`],
  [/^Building cluster (\d+)$/, (m) => `भवन समूह ${m[1]}`],
];
const original = new WeakMap();
const written = new WeakMap();
let siteLang = "en";
function translateNode(node) {
  if (!original.has(node)) original.set(node, node.nodeValue);
  const en = original.get(node); const key = en.trim();
  if (!key) return;
  let out = en;
  if (siteLang === "ne") {
    if (NE[key]) out = en.replace(key, NE[key]);
    else for (const [re, fn] of NE_PATTERNS) { const m = key.match(re); if (m) { out = en.replace(key, fn(m)); break; } }
  }
  written.set(node, out);
  if (node.nodeValue !== out) node.nodeValue = out;
}
function translateTree(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode: (n) =>
    n.parentElement && !n.parentElement.closest("script,style,#chat .msg:not(.intro),#chips,#evidenceBody code,.leaflet-control-attribution") ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) translateNode(n);
}
new MutationObserver((records) => {
  for (const r of records) {
    if (r.type === "characterData") { const n = r.target; if (written.get(n) !== n.nodeValue) { original.set(n, n.nodeValue); translateNode(n); } continue; }
    r.addedNodes.forEach((n) => (n.nodeType === 3 ? n.parentElement && translateTree(n.parentElement) : n.nodeType === 1 && translateTree(n)));
  }
}).observe(document.body, { childList: true, subtree: true, characterData: true });
function setSiteLang(lang) {
  siteLang = lang;
  document.documentElement.lang = lang === "ne" ? "ne" : "en";
  document.body.classList.toggle("ne", lang === "ne");
  $$(".sitelang button").forEach((b) => b.classList.toggle("on", b.dataset.site === lang));
  translateTree(document.body);
  const copilot = $(`.lang button[data-lang="${lang}"]`);
  if (copilot && state.lang !== lang) copilot.click();
  try { localStorage.setItem("siteLang", lang); } catch (e) { /* storage unavailable */ }
}
$$(".sitelang button").forEach((b) => b.addEventListener("click", () => setSiteLang(b.dataset.site)));
